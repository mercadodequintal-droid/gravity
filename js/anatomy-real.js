  // Polígono → caminho suave (Catmull-Rom fechado).
  function smooth(pts) {
    const n = pts.length, f = (v) => Math.round(v * 10) / 10;
    let d = `M${f(pts[0][0])} ${f(pts[0][1])}`;
    for (let i = 0; i < n; i++) {
      const p0 = pts[(i - 1 + n) % n], p1 = pts[i], p2 = pts[(i + 1) % n], p3 = pts[(i + 2) % n];
      const c1 = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6], c2 = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
      d += ` C${f(c1[0])} ${f(c1[1])} ${f(c2[0])} ${f(c2[1])} ${f(p2[0])} ${f(p2[1])}`;
    }
    return d + ' Z';
  }
  const mirror = (pts, cx) => pts.map(([x, y]) => [2 * cx - x, y]).reverse();

  // Caminhos prontos por corpo: [{ k: regiao, d: caminho }]
  const PATHS = {};
  Object.keys(BODIES).forEach((g) => {
    PATHS[g] = [];
    BODIES[g].views.forEach((v) => v.parts.forEach(([k, pts]) => {
      PATHS[g].push({ k, d: smooth(pts) });
      PATHS[g].push({ k, d: smooth(mirror(pts, v.cx)) });
    }));
  });

  const gender = () => (Store.state.settings.bodyType === 'f' ? 'f' : 'm');

