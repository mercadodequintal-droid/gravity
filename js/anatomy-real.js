  // Cada camada leva o desfoque e a mistura no próprio grupo, para misturar com a imagem de fundo.
  const layer = (parts, id, blend, op) => `<g filter="url(#${id})" style="${blend}" opacity="${op}">${parts.map((p) => `<path d="${p.d}" fill="${p.c}"/>`).join('')}</g>`;

